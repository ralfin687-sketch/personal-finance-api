-- Personal Finance API - PostgreSQL / Supabase
-- Jalankan di Supabase Dashboard > SQL Editor > New query.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  full_name varchar(120) not null check (char_length(trim(full_name)) > 0),
  email varchar(254) not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name varchar(80) not null check (char_length(trim(name)) > 0),
  type varchar(10) not null check (type in ('income', 'expense')),
  created_at timestamptz not null default now(),
  unique (name, type)
);

create table if not exists public.accounts (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  name varchar(80) not null check (char_length(trim(name)) > 0),
  account_type varchar(10) not null check (account_type in ('cash', 'bank', 'ewallet', 'other')),
  initial_balance numeric(14,2) not null default 0 check (initial_balance >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  account_id bigint not null references public.accounts(id) on delete restrict,
  category_id bigint not null references public.categories(id) on delete restrict,
  type varchar(10) not null check (type in ('income', 'expense')),
  amount numeric(14,2) not null check (amount > 0),
  description varchar(500),
  transaction_date date not null,
  created_at timestamptz not null default now()
);

create table if not exists public.budgets (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete restrict,
  amount_limit numeric(14,2) not null check (amount_limit > 0),
  period_start date not null,
  period_end date not null,
  created_at timestamptz not null default now(),
  check (period_end >= period_start)
);

create table if not exists public.savings_goals (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  name varchar(120) not null check (char_length(trim(name)) > 0),
  target_amount numeric(14,2) not null check (target_amount > 0),
  target_date date,
  created_at timestamptz not null default now()
);

create index if not exists idx_accounts_user_id on public.accounts(user_id);
create index if not exists idx_transactions_user_id on public.transactions(user_id);
create index if not exists idx_transactions_account_id on public.transactions(account_id);
create index if not exists idx_transactions_category_id on public.transactions(category_id);
create index if not exists idx_transactions_date on public.transactions(transaction_date);
create index if not exists idx_budgets_user_id on public.budgets(user_id);
create index if not exists idx_savings_goals_user_id on public.savings_goals(user_id);

